"""EDA for KuaiRand-Pure -> kb/data/eda_report.md. numpy + stdlib only.

Test split: feature-only statistics, plus ONE labelled check that merely reproduces the composition numbers the
organizers already published (27.1 % / 9.2 % / 63.7 % and oracle nDCG 0.7289) as a harness self-check.
No other test-label statistic is computed here or anywhere else (ADR-0005)."""
import csv, os, sys, collections
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.normpath(os.path.join(HERE, '..', '..', 'kuairand-starter-kit'))
sys.path.insert(0, KIT)
from evaluate import evaluate                                     # noqa: E402
D = os.path.join(KIT, 'KuaiRand-Pure', 'data')
OUT = os.path.join(HERE, 'eda_report.md')
SPLITS = {'train': (20220408, 20220421), 'valid': (20220422, 20220428), 'test': (20220429, 20220508)}
SIG = ['is_click', 'is_like', 'is_follow', 'is_comment', 'is_forward', 'is_hate']

# ---------- load ----------
vid2author = {}
with open(f'{D}/video_features_basic_pure.csv') as fh:
    r = csv.DictReader(fh); basic_cols = r.fieldnames
    for row in r: vid2author[row['video_id']] = row['author_id']
with open(f'{D}/user_features_pure.csv') as fh:
    r = csv.DictReader(fh); user_cols = r.fieldnames; n_user_rows = sum(1 for _ in r)
with open(f'{D}/video_features_statistic_pure.csv') as fh:
    stat_cols = csv.DictReader(fh).fieldnames

rows = {k: [] for k in SPLITS}                     # (user, video, date, hour, tab, y, play, dur, sigs, is_rand, time_ms)
for f in ('log_standard_4_08_to_4_21_pure.csv', 'log_standard_4_22_to_5_08_pure.csv'):
    with open(f'{D}/{f}') as fh:
        for r in csv.DictReader(fh):
            d = int(r['date'])
            for name, (lo, hi) in SPLITS.items():
                if lo <= d <= hi:
                    rows[name].append((r['user_id'], r['video_id'], d, int(r['hourmin']) // 100, r['tab'],
                                       int(r['long_view']), int(r['play_time_ms']), int(r['duration_ms']),
                                       tuple(int(r[s]) for s in SIG), int(r['is_rand']), int(r['time_ms'])))
                    break
n_random = sum(1 for _ in open(f'{D}/log_random_4_22_to_5_08_pure.csv')) - 1

md = []
P = md.append
def pct(a, b): return f'{100.0 * a / b:.1f} %'
def q(xs, ps=(10, 50, 90)): return ', '.join(f'p{p}={np.percentile(xs, p):.0f}' for p in ps)

P('# KuaiRand-Pure — measured data facts\n')
P(f'Generated by `kb/data/eda.py`. Files: `{", ".join(sorted(os.listdir(D)))}`.\n')
P('## Files and columns')
P(f'- `user_features_pure.csv`: {n_user_rows:,} users; columns: `{", ".join(user_cols)}`')
P(f'- `video_features_basic_pure.csv`: {len(vid2author):,} videos; columns: `{", ".join(basic_cols)}`')
P(f'- `video_features_statistic_pure.csv`: columns: `{", ".join(stat_cols)}` — whole-month averages, **leaky**, unused')
P(f'- `log_random_4_22_to_5_08_pure.csv`: {n_random:,} rows of random exposure (dates overlap valid + test)\n')

# ---------- per-split basics ----------
P('## Split sizes and per-user impression counts')
P('| split | rows | users | videos | authors | impressions/user mean | p10 / p50 / p90 | max |')
P('|---|---|---|---|---|---|---|---|')
per_user = {}
for name, rws in rows.items():
    c = collections.Counter(x[0] for x in rws); per_user[name] = c
    vids = {x[1] for x in rws}; auths = {vid2author.get(v, 'UNK') for v in vids}
    cnt = np.array(list(c.values()))
    P(f'| {name} | {len(rws):,} | {len(c):,} | {len(vids):,} | {len(auths):,} | {cnt.mean():.2f} | '
      f'{np.percentile(cnt,10):.0f} / {np.percentile(cnt,50):.0f} / {np.percentile(cnt,90):.0f} | {cnt.max()} |')
P('')

# ---------- labels: train + valid only ----------
P('## Label statistics (train and valid only)')
P('| split | positive rate | all-negative users | all-positive users | discriminative users | oracle nDCG@5 | oracle primary |')
P('|---|---|---|---|---|---|---|')
for name in ('train', 'valid'):
    rws = rows[name]
    byu = collections.defaultdict(lambda: [0, 0])
    for x in rws: byu[x[0]][0] += x[5]; byu[x[0]][1] += 1
    an = sum(1 for p, n in byu.values() if p == 0); ap = sum(1 for p, n in byu.values() if p == n)
    nu = len(byu); pr = sum(x[5] for x in rws) / len(rws)
    o = evaluate([x[0] for x in rws], [x[5] for x in rws], [float(x[5]) for x in rws])
    P(f'| {name} | {pr:.4f} | {pct(an, nu)} | {pct(ap, nu)} | {pct(nu - an - ap, nu)} | {o["nDCG@5"]:.4f} | {o["primary"]:.4f} |')
P('\nPublished for test (organizers): all-negative 27.1 %, all-positive 9.2 %, discriminative 63.7 %, oracle nDCG@5 0.7289.')
rws = rows['test']
byu = collections.defaultdict(lambda: [0, 0])
for x in rws: byu[x[0]][0] += x[5]; byu[x[0]][1] += 1
an = sum(1 for p, n in byu.values() if p == 0); ap = sum(1 for p, n in byu.values() if p == n); nu = len(byu)
o = evaluate([x[0] for x in rws], [x[5] for x in rws], [float(x[5]) for x in rws])
P(f'Harness self-check reproduces them: {pct(an, nu)} / {pct(ap, nu)} / {pct(nu - an - ap, nu)}, oracle nDCG@5 {o["nDCG@5"]:.4f}. '
  f'(This is the only test-label computation in the project.)\n')

# ---------- label definition ----------
tv = rows['train'] + rows['valid']
agree = sum(1 for x in tv if x[5] == int(x[6] >= min(x[7], 18000)))
P('## Label definition check')
P(f'`long_view == (play_time_ms >= min(duration_ms, 18000))` holds on {pct(agree, len(tv))} of train+valid rows '
  f'({len(tv) - agree:,} exceptions).')
comp = sum(1 for x in tv if x[6] >= x[7]); P(f'Completed plays (play_time >= duration): {pct(comp, len(tv))} of rows — the censoring the CWM paper models.')
short = sum(1 for x in tv if x[7] <= 18000); P(f'Rows whose video is <= 18 s (label = "watched to the end"): {pct(short, len(tv))}.\n')

# ---------- drift ----------
P('## Drift by date (train + valid labels; test rows only)')
P('| date | split | rows | positive rate |'); P('|---|---|---|---|')
for name in ('train', 'valid', 'test'):
    byd = collections.defaultdict(lambda: [0, 0])
    for x in rows[name]: byd[x[2]][0] += 1; byd[x[2]][1] += x[5]
    for d in sorted(byd):
        n, p = byd[d]
        P(f'| {d} | {name} | {n:,} | {"-" if name == "test" else f"{p / n:.4f}"} |')
P('')

# ---------- cold start ----------
P('## Cold start relative to train')
tr_users = set(per_user['train']); tr_vids = {x[1] for x in rows['train']}; tr_auth = {vid2author.get(v, 'UNK') for v in tr_vids}
P('| split | rows with unseen user | rows with unseen video | rows with unseen author | users with 0 train rows |'); P('|---|---|---|---|---|')
for name in ('valid', 'test'):
    rws = rows[name]; us = set(per_user[name])
    P(f'| {name} | {pct(sum(1 for x in rws if x[0] not in tr_users), len(rws))} | '
      f'{pct(sum(1 for x in rws if x[1] not in tr_vids), len(rws))} | '
      f'{pct(sum(1 for x in rws if vid2author.get(x[1], "UNK") not in tr_auth), len(rws))} | '
      f'{pct(sum(1 for u in us if u not in tr_users), len(us))} |')
hist = [per_user['train'].get(u, 0) for u in per_user['valid']]
P(f'\nTrain history depth for valid users: mean {np.mean(hist):.0f}, {q(hist)} rows.\n')

# ---------- duplicates ----------
P('## Repeated (user, video) pairs')
for name in ('valid', 'test'):
    c = collections.Counter((x[0], x[1]) for x in rows[name])
    rep = sum(n for n in c.values() if n > 1)
    P(f'- {name}: {pct(rep, len(rows[name]))} of rows belong to a repeated pair; max repeats {max(c.values())}. '
      f'(Organizers: test 3.06 %, max 12.)')
P('')

# ---------- duration ----------
P('## long_view rate by duration bucket (train; 10 train-quantile buckets as in data.py)')
durs = np.array([x[7] for x in rows['train']]); edges = np.quantile(durs, np.linspace(0, 1, 11)[1:-1])
bk = np.searchsorted(edges, durs); ys = np.array([x[5] for x in rows['train']])
P('| bucket | duration range (s) | rows | positive rate |'); P('|---|---|---|---|')
lo = 0.0
for b in range(10):
    hi = edges[b] if b < 9 else durs.max(); m = bk == b
    P(f'| {b} | {lo/1000:.1f}–{hi/1000:.1f} | {m.sum():,} | {ys[m].mean():.4f} |'); lo = hi
P('')

# ---------- other signals ----------
P('## Other feedback signals (train)')
ytr = np.array([x[5] for x in rows['train']], dtype=float)
P('| signal | rate | P(long_view=1 | signal=1) | P(signal=1 | long_view=1) | corr with long_view |'); P('|---|---|---|---|---|')
for i, s in enumerate(SIG):
    v = np.array([x[8][i] for x in rows['train']], dtype=float)
    p_lv_s = ytr[v == 1].mean() if v.sum() else float('nan'); p_s_lv = v[ytr == 1].mean()
    P(f'| {s} | {v.mean():.4f} | {p_lv_s:.4f} | {p_s_lv:.4f} | {np.corrcoef(v, ytr)[0,1]:.3f} |')
rnd = sum(x[9] for x in tv); P(f'\n`is_rand` in the standard log: {rnd} rows (should be 0).\n')

# ---------- tab / hour ----------
P('## Context (train)')
bt = collections.defaultdict(lambda: [0, 0])
for x in rows['train']: bt[x[4]][0] += 1; bt[x[4]][1] += x[5]
P('| tab | rows | share | positive rate |'); P('|---|---|---|---|')
for t in sorted(bt, key=lambda t: -bt[t][0]):
    n, p = bt[t]; P(f'| {t} | {n:,} | {pct(n, len(rows["train"]))} | {p / n:.4f} |')
bh = collections.defaultdict(lambda: [0, 0])
for x in rows['train']: bh[x[3]][0] += 1; bh[x[3]][1] += x[5]
P('\nPositive rate by hour of day: ' + ', '.join(f'{h:02d}h {bh[h][1]/bh[h][0]:.3f}' for h in sorted(bh)) + '\n')

# ---------- user behaviour around exposures (facts §10) ----------
P('## User behaviour around exposures (train; facts §10)')
tr = sorted(rows['train'], key=lambda x: (x[0], x[10]))
base = float(np.mean([x[5] for x in tr]))
grp = collections.defaultdict(list)
ua_seen = collections.defaultdict(int); ua_pos = collections.defaultdict(int); uv_seen = collections.defaultdict(int)
prev = {}; sac_by_tab = collections.Counter(); rows_by_tab = collections.Counter()
for x in tr:
    u, v, tab, y, t = x[0], x[1], x[4], x[5], x[10]
    a = vid2author.get(v, 'UNK'); p = prev.get(u); rows_by_tab[tab] += 1
    if p:
        if p[0] == a:
            sac_by_tab[tab] += 1
            grp['prev impression same author, prev long_view=1' if p[1] else 'prev impression same author, prev long_view=0'].append(y)
            grp['[label-free] prev impression same author'].append(y)
            grp[f'[label-free] prev impression same author, tab={tab}'].append(y)
            if tab == '6' and p[1]: grp['tab 6: prev same author AND prev long_view=1'].append(y)
        else:
            grp['prev impression different author, prev long_view=1' if p[1] else 'prev impression different author, prev long_view=0'].append(y)
            grp[f'[label-free] prev impression different author, tab={tab}'].append(y)
    k = (u, a); s = ua_seen[k]
    grp['[label-free] author new to this user' if s == 0 else '[label-free] author seen before by this user'].append(y)
    if s >= 3:
        r_ = ua_pos[k] / s
        grp['user x author prior long_view rate ' + ('< 0.2' if r_ < 0.2 else '0.2-0.5' if r_ < 0.5 else '>= 0.5') + ' (>= 3 prior)'].append(y)
    if uv_seen[(u, v)] > 0:
        grp['[label-free] same video shown before'].append(y); grp[f'[label-free] same video shown before, tab={tab}'].append(y)
    ua_seen[k] += 1; ua_pos[k] += y; uv_seen[(u, v)] += 1; prev[u] = (a, y)
P(f'Base P(long_view) = {base:.3f}. Rows sorted by (user, time_ms); "prev" = the same user\'s previous train impression. '
  '"[label-free]" = computable from features of earlier rows alone (usable in valid/test); the others need the previous label.\n')
P('| situation | rows | P(long_view) | lift |'); P('|---|---|---|---|')
for k in ['prev impression same author, prev long_view=1', 'prev impression same author, prev long_view=0',
          'tab 6: prev same author AND prev long_view=1',
          'prev impression different author, prev long_view=1', 'prev impression different author, prev long_view=0',
          '[label-free] prev impression same author', '[label-free] prev impression same author, tab=1',
          '[label-free] prev impression different author, tab=1', '[label-free] prev impression same author, tab=4',
          '[label-free] prev impression different author, tab=4',
          '[label-free] author new to this user', '[label-free] author seen before by this user',
          'user x author prior long_view rate < 0.2 (>= 3 prior)', 'user x author prior long_view rate 0.2-0.5 (>= 3 prior)',
          'user x author prior long_view rate >= 0.5 (>= 3 prior)',
          '[label-free] same video shown before', '[label-free] same video shown before, tab=1']:
    vals = grp.get(k, [])
    if vals: P(f'| {k} | {len(vals):,} | {np.mean(vals):.3f} | {np.mean(vals) / base:.2f}x |')
P('\nShare of rows that are same-author-consecutive, by tab (tabs with >= 2,000 rows): '
  + ', '.join(f'tab {t} {pct(sac_by_tab[t], rows_by_tab[t])}' for t in sorted(rows_by_tab, key=lambda t: -rows_by_tab[t]) if rows_by_tab[t] >= 2000))
va = sorted(rows['valid'], key=lambda x: (x[0], x[10])); prev = {}; same = new = seen3 = 0
for x in va:
    u, a = x[0], vid2author.get(x[1], 'UNK')
    same += prev.get(u) == a; new += ua_seen[(u, a)] == 0; seen3 += ua_seen[(u, a)] >= 3; prev[u] = a
P(f'\nValid (features only): previous impression by the same author {pct(same, len(va))} of rows; author never seen by the user in train '
  f'{pct(new, len(va))}; user x author with >= 3 train exposures {pct(seen3, len(va))}.\n')

open(OUT, 'w').write('\n'.join(md) + '\n')
print(f'wrote {OUT} ({len(md)} lines)')
